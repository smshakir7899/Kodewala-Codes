class Operator
{

	public static void main(String args[])
	{
	
		int x=12; //'='--> It is assignment operator not equal to (for equal we use, '==')
		System.out.println("X:" +x);
		
		/*Below is the usage of relation operator
		"==,>=,<=,<,>,!=" all these comes under relation operator
		relation operator compares values and return "boolean" results
		*/
		System.out.println(x==10);
		System.out.println(x>=10);
		System.out.println(x<=10);
	
	}

}

